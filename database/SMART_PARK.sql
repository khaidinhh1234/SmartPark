CREATE TABLE USER_ACCOUNT (     --USER_ACCOUNT – Tài khoản
    ACCOUNT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USERNAME VARCHAR2(50) NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    ROLE VARCHAR2(20) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT PK_USER_ACCOUNT
        PRIMARY KEY (ACCOUNT_ID),

    CONSTRAINT UQ_USER_ACCOUNT_USERNAME
        UNIQUE (USERNAME),

    CONSTRAINT CK_USER_ACCOUNT_ROLE
        CHECK (ROLE IN ('ADMIN', 'EMPLOYEE')),

    CONSTRAINT CK_USER_ACCOUNT_STATUS
        CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

