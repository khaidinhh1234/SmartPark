---8. PRICE_LIST – Bảng giá
CREATE TABLE PRICE_LIST (
    PRICE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    VEHICLE_TYPE_ID NUMBER NOT NULL,
    PRICE_TYPE VARCHAR2(20) NOT NULL,
    AMOUNT NUMBER(12,2) NOT NULL,
    EFFECTIVE_FROM DATE NOT NULL,
    EFFECTIVE_TO DATE,
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT PK_PRICE_LIST
        PRIMARY KEY (PRICE_ID),

    CONSTRAINT FK_PRICE_VEHICLE_TYPE
        FOREIGN KEY (VEHICLE_TYPE_ID)
        REFERENCES VEHICLE_TYPE(VEHICLE_TYPE_ID),

    CONSTRAINT CK_PRICE_TYPE
        CHECK (PRICE_TYPE IN ('HOURLY', 'MONTHLY')),

    CONSTRAINT CK_PRICE_AMOUNT
        CHECK (AMOUNT >= 0),

    CONSTRAINT CK_PRICE_STATUS
        CHECK (STATUS IN ('ACTIVE', 'INACTIVE')),

    CONSTRAINT CK_PRICE_DATE
        CHECK (
            EFFECTIVE_TO IS NULL
            OR EFFECTIVE_TO >= EFFECTIVE_FROM
        )
);
