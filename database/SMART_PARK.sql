---10. PARKING_TICKET – Lượt gửi xe
CREATE TABLE PARKING_TICKET (
    TICKET_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PARKING_TYPE VARCHAR2(20) NOT NULL,
    VEHICLE_ID NUMBER NOT NULL,
    PASS_ID NUMBER,
    SLOT_ID NUMBER NOT NULL,
    LICENSE_PLATE VARCHAR2(20) NOT NULL,
    VEHICLE_TYPE_ID NUMBER NOT NULL,
    TIME_IN DATE NOT NULL,
    TIME_OUT DATE,
    EMPLOYEE_IN_ID NUMBER NOT NULL,
    EMPLOYEE_OUT_ID NUMBER,
    TOTAL_AMOUNT NUMBER(12,2) DEFAULT 0 NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'PARKING' NOT NULL,
    CREATED_AT DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT PK_PARKING_TICKET
        PRIMARY KEY (TICKET_ID),

    CONSTRAINT FK_TICKET_VEHICLE
        FOREIGN KEY (VEHICLE_ID)
        REFERENCES VEHICLE(VEHICLE_ID),

    CONSTRAINT FK_TICKET_PASS
        FOREIGN KEY (PASS_ID)
        REFERENCES PARKING_PASS(PASS_ID),

    CONSTRAINT FK_TICKET_SLOT
        FOREIGN KEY (SLOT_ID)
        REFERENCES PARKING_SLOT(SLOT_ID),

    CONSTRAINT FK_TICKET_VEHICLE_TYPE
        FOREIGN KEY (VEHICLE_TYPE_ID)
        REFERENCES VEHICLE_TYPE(VEHICLE_TYPE_ID),

    CONSTRAINT FK_TICKET_EMP_IN
        FOREIGN KEY (EMPLOYEE_IN_ID)
        REFERENCES EMPLOYEE(EMPLOYEE_ID),

    CONSTRAINT FK_TICKET_EMP_OUT
        FOREIGN KEY (EMPLOYEE_OUT_ID)
        REFERENCES EMPLOYEE(EMPLOYEE_ID),

    CONSTRAINT CK_TICKET_TYPE
        CHECK (PARKING_TYPE IN ('PASS', 'HOURLY')),

    CONSTRAINT CK_TICKET_STATUS
        CHECK (
            STATUS IN (
                'PARKING',
                'COMPLETED',
                'CANCELLED'
            )
        ),

    CONSTRAINT CK_TICKET_AMOUNT
        CHECK (TOTAL_AMOUNT >= 0),

    CONSTRAINT CK_TICKET_TIME
        CHECK (
            TIME_OUT IS NULL
            OR TIME_OUT >= TIME_IN
        ),

    CONSTRAINT CK_TICKET_PASS_RULE
        CHECK (
            (PARKING_TYPE = 'PASS' AND PASS_ID IS NOT NULL)
            OR
            (PARKING_TYPE = 'HOURLY' AND PASS_ID IS NULL)
        )
);
