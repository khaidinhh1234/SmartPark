CREATE TABLE PAYMENT (
    PAYMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TICKET_ID NUMBER,
    PASS_ID NUMBER,
    AMOUNT NUMBER(12,2) NOT NULL,
    PAYMENT_METHOD VARCHAR2(20) NOT NULL,
    PAYMENT_TIME DATE DEFAULT SYSDATE NOT NULL,
    EMPLOYEE_ID NUMBER NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'PAID' NOT NULL,
    CREATED_AT DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT PK_PAYMENT
        PRIMARY KEY (PAYMENT_ID),

    CONSTRAINT FK_PAYMENT_TICKET
        FOREIGN KEY (TICKET_ID)
        REFERENCES PARKING_TICKET(TICKET_ID),

    CONSTRAINT FK_PAYMENT_PASS
        FOREIGN KEY (PASS_ID)
        REFERENCES PARKING_PASS(PASS_ID),

    CONSTRAINT FK_PAYMENT_EMPLOYEE
        FOREIGN KEY (EMPLOYEE_ID)
        REFERENCES EMPLOYEE(EMPLOYEE_ID),

    CONSTRAINT CK_PAYMENT_AMOUNT
        CHECK (AMOUNT >= 0),

    CONSTRAINT CK_PAYMENT_METHOD
        CHECK (PAYMENT_METHOD IN ('CASH', 'BANK', 'QR')),

    CONSTRAINT CK_PAYMENT_STATUS
        CHECK (STATUS IN ('PAID', 'REFUNDED', 'CANCELLED')),

    CONSTRAINT CK_PAYMENT_REFERENCE
        CHECK (
            (TICKET_ID IS NOT NULL AND PASS_ID IS NULL)
            OR
            (TICKET_ID IS NULL AND PASS_ID IS NOT NULL)
        )
);
